/* Generates docs/PLACEHOLDERS.md from the real data builder so the dictionary never drifts. Usage: npm run placeholders */
const fs = require('fs'), path = require('path'), vm = require('vm');
const ctx = vm.createContext({});
['Util.js', 'SeedData.js', 'Pricing.js', 'DocData.js', 'DealLogic.js'].forEach((f) => vm.runInContext(fs.readFileSync(path.join(__dirname, '..', 'src', 'server', f), 'utf8'), ctx));
const { sampleDeal, ctx: c } = require('./fixtures');
const M = ctx.masterFromSeed(ctx.SEED);
const q = ctx.buildQuote(M, sampleDeal.commercial);
let out = `# Placeholder Dictionary (Gate G3)

_Generated by \`npm run placeholders\` from \`src/server/DocData.js\`. Do not edit by hand._

## Syntax

| Syntax | Where | Effect |
|---|---|---|
| \`{{Field}}\` | anywhere (body, header, footer, tables) | Replaced with the field value |
| \`{{#IF Flag}} … {{/IF Flag}}\` | same paragraph | Text kept only if Flag is true |
| \`{{#IF Flag}}\` / \`{{/IF Flag}}\` on their own lines | separate paragraphs | Everything between is kept only if Flag is true; marker lines are removed |
| \`{{#IF !Flag}}\` … \`{{/IF Flag}}\` | either form | "Not" – kept only if Flag is false |
| \`{{EACH:List}}\` in a table row | table row | Row repeated per list item; use \`{{key}}\` in the row's cells |
| \`{{LIST:List}}\` in a paragraph/bullet | paragraph | Paragraph repeated per list item; use \`{{key}}\` inside |
| \`{{TEXT:Name}}\` | paragraph on its own | Multi-paragraph text (keeps the paragraph style) |
| \`{{TABLE:Name}}\` | paragraph on its own | Replaced by a generated, styled table (dynamic columns) |
| \`{{IMAGE:Name}}\` | paragraph | Inline image (logo) |

Rules: empty values disappear (no blanks left); any unfilled \`{{…}}\` is highlighted yellow and reported as a warning.
Amounts are already formatted (e.g. \`USD 1,800\`); dates as \`1st November 2026\`.
`;
['PROPOSAL', 'ORDER_FORM', 'MSA'].forEach((t) => {
  const d = ctx.buildDocData(t, M, sampleDeal, q, Object.assign({}, c, { docNo: { PROPOSAL: 'OC-P-2026-0001', ORDER_FORM: 'OC-Q-2026-0001', MSA: 'OC-MSA-2026-0001' }[t] }));
  out += `\n## ${t}\n\n### Fields\n| Placeholder | Sample value |\n|---|---|\n`;
  Object.keys(d.fields).forEach((k) => { out += `| \`{{${k}}}\` | ${String(d.fields[k]).replace(/\|/g, '\\|').replace(/\n/g, ' ')} |\n`; });
  out += `\n### Flags\n${Object.keys(d.flags).map((k) => `- \`${k}\` (sample: ${d.flags[k]})`).join('\n')}\n`;
  if (Object.keys(d.lists).length) out += `\n### Lists\n${Object.keys(d.lists).map((k) => `- \`${k}\`: keys ${d.lists[k][0] ? Object.keys(d.lists[k][0]).map((x) => '`{{' + x + '}}`').join(', ') : '(empty in sample)'}`).join('\n')}\n`;
  if (Object.keys(d.tables).length) out += `\n### Tables\n${Object.keys(d.tables).map((k) => `- \`{{TABLE:${k}}}\`: columns ${d.tables[k].headers.join(' · ')}`).join('\n')}\n`;
  if (Object.keys(d.texts).length) out += `\n### Texts\n${Object.keys(d.texts).map((k) => `- \`{{TEXT:${k}}}\``).join('\n')}\n`;
});
out += `\n### Images\n- \`{{IMAGE:EntityLogo}}\`: logo of the contracting entity or partner (Entities.logo_file_id)\n`;
fs.writeFileSync(path.join(__dirname, '..', 'docs', 'PLACEHOLDERS.md'), out);
console.log('docs/PLACEHOLDERS.md written');
